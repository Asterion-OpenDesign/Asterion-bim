//! Insertion of STORED elements by a document importer.
//!
//! The operations of [`crate::ops`] are the interactive rules of the reference product: a view name must be unique, a floor
//! type needs a thickness above zero, a slab sketch is validated at the call. An importer holds state a document already
//! stored, and the reference product's own stored state is not re-judged by an interactive rule. These functions insert
//! such state without the interactive checks that would refuse it, and they KEEP the checks whose failure would break the
//! model for everything else (a plan view needs an existing level, a scale outside the valid range cannot be stored, a grid
//! name is unique among grids). `ops` is untouched: the interactive paths keep their rules.
//!
//! # View names
//!
//! A view name is refused by the reference product only when the view's FORMATTED title equals the formatted title of
//! another view or view template of the document; a floor plan and a ceiling plan may both be named "L2". Storing a name
//! performs no uniqueness test ("without any uniqueness test"), the test being made by the naming helper before a rename.
//! An imported view therefore keeps its stored name whether or not another view of another class has the same one. The
//! formats are resource strings that were not specified, so the engine cannot compute a formatted title: [`import_view`]
//! makes no name test at all.

use crate::model::{
    BimModel, DetailLevel, Grid, SlabRole, SlabType, View, ViewKind, ViewRange, VisualStyle,
};
use crate::spec::{codes, MAX_VIEW_SCALE};
use asterion_core::txn::TxnContext;
use asterion_core::{ElementId, Failure};
use asterion_geom::Vec2;

/// A stored view, in engine terms.
#[derive(Clone, Debug, PartialEq)]
pub struct ImportedView {
    /// The name as stored.
    pub name: String,
    /// The engine view kind.
    pub kind: ViewKind,
    /// The integer scale (1:scale), already in 1..=24000.
    pub scale: u32,
    /// The generating level: `Some` exactly for a plan.
    pub gen_level: Option<ElementId>,
    /// The plan range (ignored by a non-plan view, which keeps the default).
    pub range: ViewRange,
    /// Crop region active.
    pub crop_active: bool,
    /// Crop region visible.
    pub crop_visible: bool,
}

/// Insert a stored view. No name test (module documentation); the level of a plan must exist and
/// a non-plan view has none; the scale must be one the engine can hold.
pub fn import_view(m: &mut BimModel, cx: &mut TxnContext<'_>, v: ImportedView) -> Result<ElementId, Failure> {
    match (v.kind.is_plan(), v.gen_level) {
        (true, None) => return Err(Failure::error(codes::VIEW_NO_LEVEL, "A plan view must be created on a level.")),
        (true, Some(l)) => {
            m.level(l)?;
        }
        (false, Some(_)) => return Err(Failure::error(codes::VIEW_NOT_PLAN, "Only plan views are generated by a level.")),
        (false, None) => {}
    }
    if v.scale == 0 || v.scale > MAX_VIEW_SCALE {
        return Err(Failure::error(codes::VIEW_BAD_SCALE, "The scale value must be between 1 and 24000."));
    }
    let id = cx.new_id();
    let range = if v.kind.is_plan() { v.range } else { ViewRange::default() };
    m.views.insert(
        id,
        View {
            id,
            name: v.name,
            kind: v.kind,
            scale: v.scale,
            // The stored detail-level value is not mapped to a name: the engine's creation default.
            detail_level: DetailLevel::Coarse,
            gen_level: v.gen_level,
            range,
            // The crop rectangle is not specified; the flags are.
            crop: None,
            crop_active: v.crop_active,
            crop_visible: v.crop_visible,
            // The view origin's frozen elevation is not bound by a row.
            origin_z: None,
            // ASSUMED defaults of `ops::create_view`.
            visual_style: if v.kind == ViewKind::ThreeD { VisualStyle::Shaded } else { VisualStyle::HiddenLine },
            // the stored display settings whose meaning is read come from the document settings (the Discipline);
            // the others are not mapped yet (crate::view_display)
            display: Default::default(),
            hidden_elements: Default::default(),
            // the stored camera is set by [`import_view_camera`]
            camera: None,
        },
    );
    Ok(id)
}

/// Refused for a view that is not 3D or whose vectors are not orthonormal (the engine does not repair a stored camera).
pub fn import_view_camera(m: &mut BimModel, view: ElementId, camera: crate::view_camera::ViewCamera) -> Result<(), Failure> {
    let v = m.view(view)?;
    if v.kind != ViewKind::ThreeD {
        return Err(Failure::error(codes::WRONG_KIND, "Only a 3D view has a camera.").on(&[view]));
    }
    if !camera.is_orthonormal() {
        return Err(Failure::error(codes::INVALID_BOUNDARY, "A stored camera's basis must be three perpendicular unit vectors.").on(&[view]));
    }
    m.views.get_mut(&view).expect("checked").camera = Some(camera);
    Ok(())
}

/// A stored straight grid, in engine terms (metres).
#[derive(Clone, Debug, PartialEq)]
pub struct ImportedGrid {
    /// The name as stored.
    pub name: String,
    /// The plan start.
    pub start: Vec2,
    /// The plan end.
    pub end: Vec2,
    /// The datum's vertical extent `(bottom, top)`, metres.
    pub vertical_extent: Option<(f64, f64)>,
}

/// Insert a stored grid. The name stays unique among grids; the automatic-name cursor
/// ([`BimModel::last_grid_name`]) is left alone (a stored document does not state it).
pub fn import_grid(m: &mut BimModel, cx: &mut TxnContext<'_>, g: ImportedGrid) -> Result<ElementId, Failure> {
    if m.grids.values().any(|x| x.name == g.name) {
        return Err(Failure::error(codes::GRID_DUPLICATE_NAME, "The name entered is already in use. Enter a unique name."));
    }
    let id = cx.new_id();
    m.grids.insert(
        id,
        Grid {
            id,
            name: g.name,
            start: g.start,
            end: g.end,
            vertical_extent: g.vertical_extent,
            bubble_in_view: Default::default(),
            through: None,
        },
    );
    Ok(id)
}

/// Insert a stored ARC grid: the plan arc from the angle of the envelope's corner 0 to that of corner 2, counter-clockwise,
/// given by its two ends and a point on it (the importer's `ArcGridSource` start / through / end, metres), with its
/// vertical extent. Same name rule as [`import_grid`].
pub fn import_arc_grid(
    m: &mut BimModel,
    cx: &mut TxnContext<'_>,
    g: ImportedGrid,
    through: Vec2,
) -> Result<ElementId, Failure> {
    if asterion_geom::Arc::from_three_points(g.start, through, g.end, crate::model::ARC_COLLINEAR_TOL_M).is_err() {
        return Err(Failure::error(codes::GRID_INVALID_ARC, "No arc passes through the grid's three points."));
    }
    let id = import_grid(m, cx, g)?;
    m.grid_mut(id)?.through = Some(through);
    Ok(id)
}

/// The engine's [`Grid::bubble_in`] answers [`Grid::DEFAULT_BUBBLE`] for a view with no entry, and the engine has no grid
/// types, so a grid whose type default differs from that constant carries the type's pair as an entry per view. Nothing is
/// stored when it equals the constant.
pub fn set_grid_type_default_bubbles(
    m: &mut BimModel,
    grid: ElementId,
    views: &[ElementId],
    bubbles: [bool; 2],
) -> Result<(), Failure> {
    if bubbles == Grid::DEFAULT_BUBBLE {
        return Ok(());
    }
    let g = m.grid_mut(grid)?;
    for v in views {
        g.bubble_in_view.insert(*v, bubbles);
    }
    Ok(())
}

