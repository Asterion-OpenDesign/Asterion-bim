/// A stored door or window TYPE, in engine terms (metres).
#[derive(Clone, Debug, PartialEq)]
pub struct ImportedHostedType {
    /// The type name as stored (the symbol's name). Two stored types may share a name (different
    /// families): the interactive uniqueness rule is not applied to stored state.
    pub name: String,
    /// Door or window (the class of the instance's specialisation object).
    pub kind: crate::model::HostedKind,
    /// The type width (the double under the width parameter), metres.
    pub width: f64,
    /// The type height, metres.
    pub height: f64,
    /// The stored thickness, metres (0 when the type stores none).
    pub thickness: f64,
    /// The stored rough width, metres (0 when absent).
    pub rough_width: f64,
    /// The stored rough height, metres (0 when absent).
    pub rough_height: f64,
}

/// Insert a stored door or window type. No name test and no registration as the category default (the document's own
/// default-type map is stored data); the cut-driving sizes must still be positive and finite, the others finite and
/// non-negative, as the model cannot hold less.
pub fn import_hosted_type(m: &mut BimModel, cx: &mut TxnContext<'_>, t: ImportedHostedType) -> Result<ElementId, Failure> {
    let bad = |label: &str, v: f64| Failure::error(codes::INSERT_BAD_SIZE, format!("The hosted type {label} is {v}."));
    for (label, v) in [("width", t.width), ("height", t.height)] {
        if !(v.is_finite() && v > crate::spec::MIN_OPENING_EXTENT_M) {
            return Err(bad(label, v));
        }
    }
    for (label, v) in [("thickness", t.thickness), ("rough width", t.rough_width), ("rough height", t.rough_height)] {
        if !(v.is_finite() && v >= 0.0) {
            return Err(bad(label, v));
        }
    }
    let id = cx.new_id();
    m.hosted_types.insert(
        id,
        crate::model::HostedType {
            id,
            name: t.name,
            kind: t.kind,
            width: t.width,
            height: t.height,
            thickness: t.thickness,
            rough_width: t.rough_width,
            rough_height: t.rough_height,
            // not stored as a built-in parameter of the type: the engine's neutral values
            default_sill_height: 0.0,
            inset: 0.0,
        },
    );
    Ok(id)
}

/// A stored door or window INSTANCE, in engine terms (metres).
#[derive(Clone, Debug, PartialEq)]
pub struct ImportedHostedInstance {
    /// The engine type.
    pub type_id: ElementId,
    /// The host wall.
    pub host: ElementId,
    /// The level the instance is associated with.
    pub level: ElementId,
    /// Metres along the host's location curve from its start.
    pub host_station: f64,
    /// Metres above the level (the stored sill height).
    pub sill_height: f64,
    /// The engine's facing flag.
    pub facing_flipped: bool,
    /// The engine's hand flag.
    pub hand_flipped: bool,
    /// The mark (the door number of a door).
    pub mark: String,
    /// The instance's own width, metres, when it stores one that differs from its type's (a width stored in the instance's
    /// own parameter store is the value the instance answers). `None` keeps the type's.
    pub width_override: Option<f64>,
    /// The instance's own height, metres (see `width_override`).
    pub height_override: Option<f64>,
    /// `None` is that rectangle.
    pub cut_loop: Option<crate::model::InstanceCutLoop>,
}

/// Insert a stored door or window instance. The host must be a wall, the type and the level must exist, the numbers must be
/// finite, an own size positive and an own cut loop finite with `min < max`. Nothing is posted at commit: the reference
/// product's own stored state (an instance on a level other than its host's, an instance whose extent leaves its host) is
/// not re-judged by the interactive rules of [`crate::ops::place_hosted_instance`].
pub fn import_hosted_instance(
    m: &mut BimModel,
    cx: &mut TxnContext<'_>,
    i: ImportedHostedInstance,
) -> Result<ElementId, Failure> {
    if !m.walls.contains_key(&i.host) {
        return Err(Failure::error(
            codes::INSERT_HOST_NOT_SUPPORTED,
            "The host element does not support the insertion of instances or openings.",
        )
        .on(&[i.host]));
    }
    m.hosted_type(i.type_id)?;
    if !m.levels.contains_key(&i.level) {
        return Err(Failure::error(codes::INSERT_NO_LEVEL, "The level the instance is placed on does not exist.").on(&[i.level]));
    }
    if !(i.host_station.is_finite() && i.sill_height.is_finite()) {
        return Err(Failure::error(codes::INSERT_BAD_STATION, "The instance station and sill height must be finite."));
    }
    for (label, v) in [("width", i.width_override), ("height", i.height_override)] {
        if let Some(v) = v {
            if !(v.is_finite() && v > crate::spec::MIN_OPENING_EXTENT_M) {
                return Err(Failure::error(codes::INSERT_BAD_SIZE, format!("The instance {label} is {v}.")));
            }
        }
    }
    if let Some(c) = i.cut_loop {
        let ok = [c.u_min, c.u_max, c.z_min, c.z_max].iter().all(|v| v.is_finite()) && c.u_min < c.u_max && c.z_min < c.z_max;
        if !ok {
            return Err(Failure::error(codes::INSERT_BAD_SIZE, "An instance cut loop must be finite with min below max on both axes."));
        }
    }
    let id = cx.new_id();
    m.hosted_instances.insert(
        id,
        crate::model::HostedInstance {
            id,
            type_id: i.type_id,
            host: i.host,
            level: i.level,
            host_station: i.host_station,
            sill_height: i.sill_height,
            facing_flipped: i.facing_flipped,
            hand_flipped: i.hand_flipped,
            mark: i.mark,
            width_override: i.width_override,
            height_override: i.height_override,
            cut_loop: i.cut_loop,
        },
    );
    Ok(id)
}

/// Insert a rectangular wall opening derived from stored state (the extent of a door's or window's cut loop): host station
/// range `u` and absolute elevation range `z`, metres, both normalised. The interactive checks of
/// [`crate::ops::add_rectangular_opening`] (extent, fit, "does not cut" warning) are not applied: the rectangle is stored
/// state, and a rectangle that leaves its host is clipped by the regeneration.
pub fn import_wall_opening(
    m: &mut BimModel,
    cx: &mut TxnContext<'_>,
    host: ElementId,
    u: (f64, f64),
    z: (f64, f64),
) -> Result<ElementId, Failure> {
    if !m.walls.contains_key(&host) {
        return Err(Failure::error(
            codes::INSERT_HOST_NOT_SUPPORTED,
            "The host element does not support the insertion of instances or openings.",
        )
        .on(&[host]));
    }
    if ![u.0, u.1, z.0, z.1].iter().all(|v| v.is_finite()) {
        return Err(Failure::error(codes::OPENING_INVALID_BOUNDARY, "The opening corners must be finite.").on(&[host]));
    }
    let (u_min, u_max, z_min, z_max) = (u.0.min(u.1), u.0.max(u.1), z.0.min(z.1), z.0.max(z.1));
    let id = cx.new_id();
    m.wall_openings.insert(id, crate::model::WallOpening { id, host, u_min, u_max, z_min, z_max });
    Ok(id)
}

/// A stored room, in engine terms (metres).
#[derive(Clone, Debug, PartialEq)]
pub struct ImportedRoom {
    /// The level (the element's associated level).
    pub level: ElementId,
    /// The seed point.
    pub point: Vec2,
    /// Base offset above the level, metres.
    pub base_offset: f64,
    /// Limit offset above the upper limit, metres.
    pub limit_offset: f64,
    /// The upper limit level; `None` reads as the room's own level.
    pub upper_limit: Option<ElementId>,
    /// The name (without the number).
    pub name: String,
    /// The number as stored (not necessarily numeric).
    pub number: String,
    /// A room tag names this room.
    pub tagged: bool,
}

/// Insert a stored room. The level and the upper limit must exist; the number cursor of the model
/// ([`BimModel::last_room_number`]) is left alone (a stored document does not state it), and no
/// placement rule is applied (a room is kept whether or not its point is enclosed).
pub fn import_room(m: &mut BimModel, cx: &mut TxnContext<'_>, r: ImportedRoom) -> Result<ElementId, Failure> {
    m.level(r.level)?;
    if let Some(u) = r.upper_limit {
        m.level(u)?;
    }
    if !(r.base_offset.is_finite() && r.limit_offset.is_finite() && r.point.x.is_finite() && r.point.y.is_finite()) {
        return Err(Failure::error(codes::INSERT_BAD_STATION, "A room's point and offsets must be finite lengths."));
    }
    let id = cx.new_id();
    m.rooms.insert(
        id,
        crate::model::Room {
            id,
            level: r.level,
            point: r.point,
            base_offset: r.base_offset,
            limit_offset: r.limit_offset,
            upper_limit: r.upper_limit,
            name: r.name,
            number: r.number,
            tagged: r.tagged,
        },
    );
    Ok(id)
}

