    /// A stored room is kept as stored (tag flag, number text, upper limit), and the number cursor is left alone.
    #[test]
    fn spec_a_stored_column_keeps_its_references_offsets_and_flags() {
        // The flips
        let ft = 0.3048;
        let mut doc = new_document();
        let out = doc.transact("import", false, |m, cx| {
            let l = ops::create_level(m, cx, "L1", 0.0)?;
            let ty = crate::columns::create_column_type(m, cx, "C", None, None)?;
            let mut stored = ImportedColumn {
                type_id: ty,
                base_level: l,
                base_offset: -0.656167979 * ft,
                top_level: Some(l),
                top_offset: 1.640419948 * ft,
                location: Vec2::new(6.5617 * ft, 6.5617 * ft),
                location_z: 0.0,
                rotation: std::f64::consts::FRAC_PI_2 + std::f64::consts::TAU,
                moves_with_grids: true,
                room_bounding: true,
            };
            let id = import_column(m, cx, stored)?;
            let c = m.column(id)?.clone();
            assert!((c.rotation - std::f64::consts::FRAC_PI_2).abs() < 1e-12 && c.moves_with_grids && c.room_bounding && !c.mirrored());
            let s = crate::columns::column_state(m, &c)?;
            assert!((s.base_z + 0.2).abs() < 1e-8 && (s.top_z - 0.5).abs() < 1e-8 && (s.length - 0.7).abs() < 1e-8);
            // the stored flips: exactly one makes the column mirrored
            crate::columns::set_column_flips(m, id, true, false)?;
            assert!(m.column(id)?.mirrored());
            crate::columns::set_column_flips(m, id, true, true)?;
            assert!(!m.column(id)?.mirrored());
            // a missing level or type is refused; a top below the base is stored state, kept
            stored.base_level = ElementId(999);
            assert_eq!(import_column(m, cx, stored).unwrap_err().code, codes::NOT_FOUND);
            stored.base_level = l;
            stored.top_offset = -5.0;
            let id2 = import_column(m, cx, stored)?;
            assert!(crate::columns::column_state(m, m.column(id2)?)?.volume == 0.0);
            Ok(())
        });
        assert!(out.committed(), "{:?}", out.failures);
    }

