/// A stored stairs element, in engine terms; metres.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct ImportedStairs {
    /// The engine stairs type.
    pub type_id: ElementId,
    /// Base and top levels.
    pub base_level: ElementId,
    pub top_level: ElementId,
    /// The stored actual riser height.
    pub actual_riser_height: f64,
    pub actual_tread_depth: f64,
    pub user_changed_riser_height: bool,
}

/// Insert a stored stairs. Neither the creation rule (riser count from the type) nor the regeneration
/// step is run: the riser height and tread depth are the stored ones (a stored document is not
/// re-judged). The type and both levels must exist and the stored numbers be finite.
pub fn import_stairs(m: &mut BimModel, cx: &mut TxnContext<'_>, s: ImportedStairs) -> Result<ElementId, Failure> {
    m.stairs.stairs_type(s.type_id)?;
    m.level(s.base_level)?;
    m.level(s.top_level)?;
    if !(s.actual_riser_height.is_finite() && s.actual_tread_depth.is_finite()) {
        return Err(Failure::error(codes::INSERT_BAD_SIZE, "A stairs' riser height and tread depth must be finite."));
    }
    let id = cx.new_id();
    m.stairs.stairs.insert(
        id,
        crate::stairs::Stairs {
            id,
            type_id: s.type_id,
            base_level: s.base_level,
            top_level: s.top_level,
            actual_riser_height: s.actual_riser_height,
            actual_tread_depth: s.actual_tread_depth,
            user_changed_riser_height: s.user_changed_riser_height,
            riser_count_floor: None,
            multistory_member: false,
        },
    );
    Ok(id)
}

