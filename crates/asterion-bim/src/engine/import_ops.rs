/// Insert a stored viewport: the sheet and the view must exist; the one-sheet-per-view rule of the interactive create is
/// not tested (the stored state is kept); `center` is the stored viewport origin on the sheet (metres) and `rotation` one
/// of "None", "Clockwise", "Counterclockwise".
pub fn import_viewport(m: &mut BimModel, cx: &mut TxnContext<'_>, sheet: ElementId, view: ElementId, center: [f64; 2], rotation: &str) -> Result<ElementId, Failure> {
    if !m.docs.sheets.contains_key(&sheet) {
        return Err(Failure::error(codes::NOT_FOUND, "No such sheet.").on(&[sheet]));
    }
    m.view(view)?;
    if !(center[0].is_finite() && center[1].is_finite()) {
        return Err(Failure::error(codes::INSERT_BAD_SIZE, "A viewport's position must be finite."));
    }
    let id = cx.new_id();
    m.docs.viewports.insert(id, crate::sheets::Viewport { id, sheet, view, center, rotation: rotation.to_owned(), label_offset: None });
    Ok(id)
}

/// Insert a stored schedule definition. A stored document is not re-judged: the name need not be unique and the fields are
/// the ones the caller translated; every filter and sort field index must be inside the field list.
pub fn import_schedule(m: &mut BimModel, cx: &mut TxnContext<'_>, mut s: crate::schedules::Schedule) -> Result<ElementId, Failure> {
    let n = s.fields.len();
    if s.filters.iter().any(|f| f.field >= n) || s.sort.iter().any(|f| f.field >= n) {
        return Err(Failure::error(codes::SCHEDULE_INVALID, "A schedule filter or sort refers to a field the schedule does not have."));
    }
    s.id = cx.new_id();
    let id = s.id;
    m.docs.schedules.insert(id, s);
    Ok(id)
}

/// Insert a stored schedule instance (a schedule placed on a sheet); `point` in metres.
pub fn import_schedule_instance(m: &mut BimModel, cx: &mut TxnContext<'_>, sheet: ElementId, schedule: ElementId, point: [f64; 2]) -> Result<ElementId, Failure> {
    if !m.docs.sheets.contains_key(&sheet) {
        return Err(Failure::error(codes::NOT_FOUND, "No such sheet.").on(&[sheet]));
    }
    if !m.docs.schedules.contains_key(&schedule) {
        return Err(Failure::error(codes::NOT_FOUND, "No such schedule.").on(&[schedule]));
    }
    let id = cx.new_id();
    m.docs.schedule_instances.insert(id, crate::sheets::ScheduleInstance { id, sheet, schedule, point });
    Ok(id)
}

